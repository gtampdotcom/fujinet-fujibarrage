#!/usr/bin/env python3
"""tools/nabu/build.py -- FujiBarrage for the NABU PC (z88dk +nabu, zsdcc at
-SO2: -SO3 miscompiles, as on the Adam). No make needed; build-nabu.bat runs
this.

    python tools/nabu/build.py                 r2r/nabu/fujinet-barrage.nabu
    python tools/nabu/build.py clean
    SERVER=host:port                           the rooms listed (gen/config.h; default fujinet.online:9913)
    TEST_SCENE=n TEST_ARG=a                    a scene built in (src/test.c)
    VIDEO_CARD=1                               M0's test card
    DEBUG=1                                    messages on the adapter's console
    XFLAGS=-D...                               more flags, both programs
    LOCAL_DIR=dir                              a copy goes there (default
                                               c:\\nabu\\local, if it exists)

One program (-DONE_PROGRAM, src/main.c): the Adam's two, the game and the
menu (the title, the name, the room list), fit the NABU's RAM together. It
loads at 0000h (z88dk's NABU crt moves it there), its variables above it,
then the field's store (src/tms9918/fld.asm, SHADOW_ORG here), the stack
and z88dk's interrupt table at FF00h.
"""
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
Z88DK = os.environ.get("Z88DK_DIR", "c:\\z88dk\\")
B = os.path.join(ROOT, "build", "nabu")
R = os.path.join(ROOT, "r2r", "nabu")
G = os.path.join(ROOT, "gen", "nabu")
PY = sys.executable

# Memory: the program from 0000h, its variables above it, then the field's
# store (src/tms9918/fld.asm: 2A00h bytes, a page-aligned 256 x 168 in two
# planes; the title's 1800h unpacking buffer before a room), then the stack
# (z88dk's: down from FF00h; the Adam's game used 178 bytes) and z88dk's IM 2
# table at FF00h.
SHADOW_ORG = 0xD000
SHADOW_LEN = 0x2A00
STACK_MIN = 0x400               # bytes the stack has, at least

SHARED = ["src/main.c", "src/menus.c", "src/nabu/appkey.c", "src/net.c", "src/cat.c"]
GAME = ["src/play.c", "src/room.c", "src/test.c", "src/tms9918/field.asm", "src/tms9918/fld.asm",
        "src/tms9918/render.asm", "gen/nabu/fldart.asm", "gen/nabu/tunes.asm",
        "src/z80/ply.asm", "src/z80/trk.asm", "src/z80/ops.asm", "src/z80/pt.asm"]
COMMON = ["src/nabu/plat.c", "src/nabu/input.c", "src/nabu/nstrans.c", "src/nabu/hcca.c",
          "src/nabu/dbg.c", "src/nabu/irq.asm", "src/nabu/vdp.asm", "src/nabu/nabu_hw.asm",
          "src/nabu/art.asm", "src/nabu/ay.asm", "src/nabu/f18a.c", "src/tms9918/scr.asm", "src/tms9918/card.c",
          "src/sound/snd.asm", "gen/nabu/sfx.asm"]
MENU = ["src/tms9918/title.asm", "src/tms9918/lzd.asm",
        "gen/nabu/title.asm"]
PROGS = {"barrage": SHARED + GAME + COMMON + MENU}


def run(cmd, **kw):
    print(" ".join(cmd) if os.environ.get("V") else "  " + cmd[-1])
    r = subprocess.run(cmd, cwd=ROOT, **kw)
    if r.returncode:
        sys.exit("build.py: failed: " + " ".join(cmd))


def gen():
    os.makedirs(G, exist_ok=True)
    tasks = [
        ("fldart.asm", ["tools/mkgfx_tms.py", "field"]),
        ("art.bin", ["tools/mkgfx_tms.py", "art"]),
        ("title.asm", ["tools/mkgfx_tms.py", "title"]),
        ("sfx.asm", ["tools/mksfx_z80.py", "sfx"]),
        ("copper.h", ["tools/nabu/mkcopper.py"]),
        ("tunes.asm", ["tools/mksfx_z80.py", "tunes", None, "title=music/title.txt",
                       "win=music/win.txt", "over=music/over.txt", "shop=music/shop.txt"]),
    ]
    for out, args in tasks:
        path = "gen/nabu/" + out
        if os.path.exists(os.path.join(ROOT, path)) and                 os.path.getmtime(os.path.join(ROOT, path)) > os.path.getmtime(os.path.join(ROOT, args[0])):
            continue
        a = [x if x is not None else path for x in args]
        if None not in args:
            a.append(path)
        print("Making " + path)
        r = subprocess.run([PY] + a, cwd=ROOT)
        if r.returncode:
            sys.exit("build.py: " + out)
    server = os.environ.get("SERVER")
    sf = os.path.join(ROOT, "gen", "server")
    if server:
        open(sf, "w").write(server + "\n")
    if not os.path.exists(sf):
        open(sf, "w").write("fujinet.online:9913\n")
    server = open(sf).read().strip()
    cfg = '/* GENERATED by tools/nabu/build.py. */\n#define DEFAULT_SERVER "%s"\n' % server
    cp = os.path.join(ROOT, "gen", "config.h")
    if not os.path.exists(cp) or open(cp).read() != cfg:
        open(cp, "w").write(cfg)
    return server


def build(prog, srcs, flags):
    od = os.path.join(B, prog)
    os.makedirs(od, exist_ok=True)
    # the flags a program was built with: changed, its objects build again
    ff = os.path.join(B, prog + ".flags")
    fl = " ".join(flags)
    if not os.path.exists(ff) or open(ff).read() != fl:
        shutil.rmtree(od)
        os.makedirs(od)
        open(ff, "w").write(fl)
    deps = [os.path.getmtime(os.path.join(ROOT, p)) for d in
            ("src", "src/platform-specific", "src/nabu", "src/tms9918", "src/z80", "gen", "gen/nabu")
            for p in [os.path.join(d, f) for f in os.listdir(os.path.join(ROOT, d))]
            if re.search(r"\.(h|inc|bin)$", p)]
    newest = max(deps)
    objs = []
    for s in srcs:
        o = os.path.join(od, s.replace("/", "_").rsplit(".", 1)[0] + ".o")
        objs.append(o)
        if os.path.exists(o) and os.path.getmtime(o) > max(newest, os.path.getmtime(os.path.join(ROOT, s))):
            continue
        cmd = ["zcc"] + flags + ["-c", "-o", o, s]
        if s.endswith(".asm"):
            cmd[1:1] = ["-Ca-Isrc/z80", "-Ca-Isrc/nabu", "-Ca-Isrc", "-Ca-Igen/nabu",
                        "-Ca-DSHADOW_ORG=0x%04X" % SHADOW_ORG, "-Ca-DTITLE_BUF=0x%04X" % SHADOW_ORG, "-Ca-DART_RAM",
                        "-Ca-DF18A_HOOK"]
        run(cmd)
    out = os.path.join(od, prog + ".nabu")
    run(["zcc", "+nabu", "-vn", "-compiler=sdcc", "-m",
         "-pragma-define:CRT_INITIALIZE_BSS=1", "-pragma-define:CRT_TRIM_BSS=1",
         "-pragma-define:CLIB_DEFAULT_SCREEN_MODE=-1", "-pragma-define:CRT_ENABLE_STDIO=0",
         "-pragma-redirect:fputc_cons=_fputc_cons_stub", "-create-app"] + objs + ["-o", out])
    return out


def symbols(mapf):
    syms = {}
    for line in open(mapf):
        m = re.match(r"(\S+)\s+=\s+\$([0-9A-Fa-f]{4,})\s", line)
        if m:
            syms[m.group(1)] = int(m.group(2), 16)
    return syms


def main():
    if len(sys.argv) > 1 and sys.argv[1] == "clean":
        shutil.rmtree(B, ignore_errors=True)
        shutil.rmtree(R, ignore_errors=True)
        print("Cleaned.")
        return
    os.environ["ZCCCFG"] = os.path.join(Z88DK, "lib", "config") + os.sep
    os.environ["PATH"] = os.path.join(Z88DK, "bin") + os.pathsep + os.environ["PATH"]
    server = gen()
    print("Building FujiBarrage for the NABU PC (server %s)" % server)
    cflags = ["+nabu", "-vn", "-compiler=sdcc", "-SO2", "-D__NABU__",
              "-Isrc", "-Isrc/platform-specific", "-Isrc/nabu", "-Isrc/tms9918", "-Isrc/z80",
              "-Igen", "-Igen/nabu"]
    if os.environ.get("DEBUG") == "1":
        cflags.append("-DNABU_DEBUG")
    if os.environ.get("VIDEO_CARD") == "1":
        cflags.append("-DVIDEO_CARD")
    cflags += os.environ.get("XFLAGS", "").split()
    game_fl = []
    if os.environ.get("TEST_SCENE"):
        game_fl = ["-DTEST_SCENE=" + os.environ["TEST_SCENE"], "-DTEST_ARG=" + os.environ.get("TEST_ARG", "0")]
    outs = {}
    for prog, srcs in PROGS.items():
        print("%s:" % prog)
        outs[prog] = build(prog, srcs, cflags + ["-DONE_PROGRAM"] + game_fl)
    for prog in PROGS:
        mp = outs[prog][:-5] + ".map"
        s = symbols(mp)
        end = s.get("__BSS_END_tail", 0)
        print("%s: %d bytes; code and data to %04X, variables to %04X (the field's store at %04X: %d free)" %
              (prog, os.path.getsize(outs[prog]), s.get("__DATA_END_tail", 0), end, SHADOW_ORG,
               SHADOW_ORG - end))
        if end > SHADOW_ORG:
            sys.exit("build.py: the variables reach the field's store")
        if 0xFF00 - (SHADOW_ORG + SHADOW_LEN) < STACK_MIN:
            sys.exit("build.py: the stack is too small")
        if os.path.getsize(outs[prog]) > 60401:
            sys.exit("build.py: over the 60401 bytes a .nabu can be")
    os.makedirs(R, exist_ok=True)
    out = os.path.join(R, "fujinet-barrage.nabu")
    shutil.copyfile(outs["barrage"], out)
    print("Built " + out)
    local = os.environ.get("LOCAL_DIR", r"c:\nabu\local")
    if os.path.isdir(local):
        shutil.copyfile(out, os.path.join(local, "fujinet-barrage.nabu"))
        print("Copied to " + local)


if __name__ == "__main__":
    main()
